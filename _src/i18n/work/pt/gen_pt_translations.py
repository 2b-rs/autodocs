def main():
    batch_file = os.path.join(os.path.dirname(__file__), "batch_01.jsonl")
    out_file = os.path.join(os.path.dirname(__file__), "batch_99.out.jsonl")

    with open(batch_file, "r", encoding="utf-8") as f:
        rows = [json.loads(line) for line in f if line.strip()]

    print("Read %d rows from batch_01.jsonl" % len(rows))
    missing = [r["id"] for r in rows if r["id"] not in PT_TRANSLATIONS]
    if missing:
        print("ERROR: missing %d translations: %s" % (len(missing), missing[:5]))
        sys.exit(1)

    # Validate each row against pruefe
    errors = []
    output_rows = []
    for idx, r in enumerate(rows, 1):
        id_ = r["id"]
        de = r["de"]
        t = PT_TRANSLATIONS[id_]
        err = i18n_translate.pruefe(de, t)
        if err:
            errors.append((idx, id_, err))
        output_rows.append({"id": id_, "t": t})

    if errors:
        print("ERROR: %d validation errors found:" % len(errors))
        for idx, id_, err in errors[:10]:
            print("  line %d, id %s: %s" % (idx, id_, err))
        sys.exit(1)

    print("All %d rows passed validation!" % len(output_rows))
    with open(out_file, "w", encoding="utf-8") as f:
        for r in output_rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print("Wrote %d rows to %s" % (len(output_rows), out_file))


if __name__ == "__main__":
    main()
